'use client';

import React, { useMemo } from 'react';
import katex from 'katex';
import 'katex/dist/katex.min.css';
import { splitMathSegments } from '@/lib/math-text';

/** Render one LaTeX formula to HTML with KaTeX. Never throws. */
export function renderLatexToHtml(latex: string, displayMode: boolean): { html: string; error: string | null } {
  try {
    const html = katex.renderToString(latex, {
      displayMode,
      throwOnError: true,
      strict: 'ignore',
      trust: false,
      output: 'htmlAndMathml',
    });
    return { html, error: null };
  } catch (e: any) {
    const msg = String(e?.message || e).replace(/^KaTeX parse error:\s*/, '');
    return { html: '', error: msg };
  }
}

export const MathFormula: React.FC<{ latex: string; display?: boolean; className?: string }> = ({
  latex,
  display = false,
  className,
}) => {
  const { html, error } = useMemo(() => renderLatexToHtml(latex, display), [latex, display]);
  if (error) {
    return (
      <code
        className={`px-1 rounded bg-red-50 text-red-700 border border-red-200 text-[0.85em] ${className || ''}`}
        title={error}
        data-testid="math-error"
      >
        {latex}
      </code>
    );
  }
  return (
    <span
      className={className}
      data-testid={display ? 'math-display' : 'math-inline'}
      // KaTeX output is generated by a trusted renderer with trust:false.
      dangerouslySetInnerHTML={{ __html: html }}
    />
  );
};

/** Paragraph text with inline ($..$) and display ($$..$$) formulas rendered. */
export const MathText: React.FC<{ text: string }> = ({ text }) => {
  const segments = useMemo(() => splitMathSegments(text), [text]);
  return (
    <>
      {segments.map((seg, i) =>
        seg.kind === 'text' ? (
          <React.Fragment key={i}>{seg.value}</React.Fragment>
        ) : (
          <MathFormula
            key={i}
            latex={seg.value}
            display={seg.kind === 'display'}
            className={seg.kind === 'display' ? 'block my-1 text-center' : undefined}
          />
        )
      )}
    </>
  );
};
