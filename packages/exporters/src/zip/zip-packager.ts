/**
 * Submission Package ZIP Packager for StructPaper v2
 *
 * Compiles a complete submission bundle archive containing:
 * - manuscript.tex (XeLaTeX source)
 * - structpaper-hs.cls (Template document class)
 * - images/ (Extracted figures and graphic assets)
 * - metadata.json (Frontmatter metadata)
 * - README.md (Compilation & submission instructions)
 * - manuscript.xml (JATS XML 1.3 representation)
 * - manuscript.docx (Microsoft Word document, optional)
 */

import JSZip from 'jszip';
import type { Manuscript } from '@structpaper/doc-model';
import type { JournalProfile } from '@structpaper/journal-profiles';
import { LatexExporter, type LatexExportOptions } from '../latex/latex-exporter';
import { JatsExporter, type JatsExportOptions } from '../jats/jats-exporter';
import { DocxExporter, type DocxExportOptions } from '../docx/docx-exporter';

export interface ZipPackagerOptions {
  profile?: JournalProfile;
  latexOptions?: LatexExportOptions;
  jatsOptions?: JatsExportOptions;
  docxOptions?: DocxExportOptions;
  assets?: Record<string, Uint8Array | Buffer>;
  includeJats?: boolean;
  includeDocx?: boolean;
  customReadme?: string;
}

const DEFAULT_README = `# StructPaper v2 Submission Bundle

This archive was automatically generated by StructPaper v2.
It contains all necessary source files and assets to compile the paper into high-quality camera-ready PDF.

## Archive Contents
- \`manuscript.tex\`: Standalone XeLaTeX source code
- \`structpaper-hs.cls\`: Document class adhering to journal guidelines
- \`images/\`: Graphics and figures referenced in the manuscript
- \`metadata.json\`: Paper metadata in structured JSON format
- \`manuscript.xml\`: Standard NLM/NCBI JATS XML 1.3 archive
- \`README.md\`: This guide

## Compilation Instructions

### 1. Using Tectonic (Recommended, Zero-Setup)
If Tectonic is installed:
\`\`\`bash
tectonic manuscript.tex
\`\`\`

### 2. Using XeLaTeX / TeX Live
\`\`\`bash
xelatex manuscript.tex
bibtex manuscript
xelatex manuscript.tex
xelatex manuscript.tex
\`\`\`

Requires Times New Roman font and standard TeX Live / MacTeX distributions.
`;

export class ZipPackager {
  private latexExporter = new LatexExporter();
  private jatsExporter = new JatsExporter();
  private docxExporter = new DocxExporter();

  /**
   * Constructs a populated JSZip instance containing the submission package.
   */
  public async buildZip(
    manuscript: Manuscript,
    options: ZipPackagerOptions = {}
  ): Promise<JSZip> {
    const zip = new JSZip();

    // 1. manuscript.tex
    const texSource = this.latexExporter.export(manuscript, {
      profile: options.profile,
      ...options.latexOptions,
    });
    zip.file('manuscript.tex', texSource);

    // 2. structpaper-hs.cls
    try {
      const clsSource = LatexExporter.getTemplateCls();
      zip.file('structpaper-hs.cls', clsSource);
    } catch {
      // If template not found on disk, omit or let test handle
    }

    // 3. images/ assets
    const imagesFolder = zip.folder('images');
    if (imagesFolder && options.assets) {
      for (const [assetId, assetData] of Object.entries(options.assets)) {
        const meta = manuscript.assets?.[assetId];
        const ext =
          meta?.mimeType === 'image/jpeg'
            ? 'jpg'
            : meta?.mimeType === 'image/svg+xml'
              ? 'svg'
              : 'png';
        const fileName = meta?.fileName || `${assetId}.${ext}`;
        imagesFolder.file(fileName, assetData);
      }
    }

    // 4. metadata.json
    const metadata = {
      id: manuscript.id,
      lang: manuscript.lang,
      journalId: manuscript.journalId,
      articleType: manuscript.articleType,
      meta: manuscript.meta,
      exportTimestamp: new Date().toISOString(),
    };
    zip.file('metadata.json', JSON.stringify(metadata, null, 2));

    // 5. README.md
    zip.file('README.md', options.customReadme || DEFAULT_README);

    // 6. manuscript.xml (JATS XML 1.3)
    if (options.includeJats !== false) {
      const jatsSource = this.jatsExporter.export(
        manuscript,
        options.jatsOptions
      );
      zip.file('manuscript.xml', jatsSource);
    }

    // 7. manuscript.docx (optional)
    if (options.includeDocx) {
      const docxBuffer = await this.docxExporter.exportToBuffer(
        manuscript,
        options.docxOptions
      );
      zip.file('manuscript.docx', docxBuffer);
    }

    return zip;
  }

  /**
   * Packages the entire submission bundle and returns it as a binary Buffer.
   */
  public async package(
    manuscript: Manuscript,
    options: ZipPackagerOptions = {}
  ): Promise<Buffer> {
    const zip = await this.buildZip(manuscript, options);
    return await zip.generateAsync({
      type: 'nodebuffer',
      compression: 'DEFLATE',
      compressionOptions: { level: 6 },
    });
  }
}
